/**
 * 领域：客服
 *
 * 这个领域值得单列，因为它是 **Jev 官方最典型的用例**：Jev 官方文档与多个 cookbook
 * 都拿「把客服工单分流到哪个队列」当第一个例子（"Which team should handle this?"）。
 * 它的形态和学科类领域根本不同：
 *
 *  - **判的是「客户要什么」，不是「问题是什么」**。客户说「质量太差，退我钱」，
 *    诉求是**退款**（资金流程），而不是「产品质量」；按后者分流会把工单送错队列。
 *  - **有明确的分流优先级**。一条消息同时抱怨物流和钱时，流程上先处理资金诉求——
 *    这条规则必须写进判题要点，否则模型会按「消息里先提到哪个」来判断。
 *  - **「其他」是兜底，被选中就说明分类体系没覆盖**。所以本域把「其他被选中要人工复核」
 *    写成判题要点，而不是让它安静地落到兜底队列里。
 *
 * 与「常识」领域的边界：常识判的是**知识对不对**（这样做安不安全），
 * 客服判的是**诉求归到哪个流程**（这条消息该谁处理）。措辞上，出现订单、工单、
 * 客户、退换货等交易语汇倾向客服；出现「能不能/应该怎么/正确做法」倾向常识。
 */

